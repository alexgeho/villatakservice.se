def hero_alt(base):
    """Alt för bild -1 (hero) eller None."""
    if base.startswith("taklaggare-") and base[len("taklaggare-"):] in ORT:
        return ORT[base[len("taklaggare-"):]]
    return TOPIC.get(base)


def detail_alt(base):
    """Alt för bild -2 på ämnessidor («detail view» av samma motiv) eller None."""
    t = TOPIC.get(base)
    if not t:
        return None
    return t if t.startswith("Närbild") else f"Närbild: {t[0].lower() + t[1:]}"
